import inspect
import gc
import collections

print(type(inspect))
print(type(gc))
print(type(collections))
print(gc.__file__)

frame = inspect.currentframe()
print(type(frame))
print(inspect.isframe(frame))
print(inspect.isfunction(inspect.currentframe))
print(inspect.iscode(frame.f_code))
print(frame.f_code.co_name)
print(frame.f_code.co_filename.__contains__('stdlib_modules.py'))
print(type(frame.f_locals))
print(type(frame.f_globals))
print(type(frame.f_builtins))
print(frame.f_lineno > 0)
print(frame.f_code.co_stacksize >= 1)
print(type(frame.f_code.co_consts))
print(type(frame.f_code.co_names))
print(type(frame.f_code.co_varnames))

counts_before = gc.get_count()
print(type(counts_before))
print(len(counts_before))
removed = gc.collect()
counts_after = gc.get_count()
print(type(removed))
print(removed >= 0)
print(counts_after[0] <= counts_before[0])
objects = gc.get_objects()
print(type(objects))
print(len(objects) > 0)
print(gc.isenabled())

Point = collections.namedtuple('Point', 'x y')
p = Point(3, 4)
print(type(Point))
print(type(p))
print(issubclass(Point, tuple))
print(isinstance(p, tuple))
print(p.x)
print(p.y)
print(p[0])
print(p[1])
print(Point._fields)
print(Point.__match_args__)

