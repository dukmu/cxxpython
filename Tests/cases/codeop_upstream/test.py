for line, source, symbol, expected in SAMPLES:
    try:
        value = compile_command(source, symbol=symbol)
        result = 'incomplete' if value is None else 'code'
    except Exception as error:
        result = type(error).__name__
        category = 'SyntaxError' if isinstance(error, SyntaxError) else result
    else:
        category = result
    print(line, symbol, result)
    assert category == expected, (line, source, result, expected)
