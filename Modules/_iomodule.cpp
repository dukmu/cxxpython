struct StdTextIO {
    ObjectHeader header;
    const int fd;
    std::mutex mutex;
    std::condition_variable idle;
    bool closed = false;
    std::size_t active = 0;
    StdTextIO(InitialType head, int descriptor) : header(head), fd(descriptor) {}
    void trace(Tracer &) const noexcept {}
};
bool failed(ReturnSlot &out)
{
    return out.tag() == ResultTag::Raised;
}
bool is_text(Attachment &ctx, Value value)
{
    return ctx.has_layout<StrObject>(value) &&
           is_subtype(ctx, ctx.type_of(value), ctx.builtin(CoreObject::StrType));
}
void io_error(Attachment &ctx, ReturnSlot &out)
{
    raise_error(ctx, CoreObject::OSErrorType, U"standard stream operation failed", out);
}
void closed_error(Attachment &ctx, ReturnSlot &out)
{
    raise_error(ctx, CoreObject::ValueErrorType, U"I/O operation on closed file", out);
}
void write_entry(Attachment &ctx, Handle, std::span<const Value> args, ReturnSlot &out)
{
    if (!is_text(ctx, args[1])) {
        raise_error(ctx, CoreObject::TypeErrorType, U"write() argument must be str", out);
        return;
    }
    RootScope roots(ctx);
    auto self = roots.root(args[0]);
    auto text = roots.root(args[1]);
    auto &stream = ctx.payload<StdTextIO>(self);
    bool closed;
    {
        NativeWait wait(ctx);
        std::lock_guard lock(stream.mutex);
        closed = stream.closed;
    }
    if (closed) {
        closed_error(ctx, out);
        return;
    }
    auto none = roots.root(ctx.builtin(CoreObject::None));
    ReturnSlot encoded(ctx);
    detail::encode_text(ctx, text, none, none, encoded);
    if (failed(encoded)) {
        out.raised(encoded.exception());
        return;
    }
    auto bytes = roots.root(encoded.value());
    const auto &data = ctx.payload<BytesObject>(bytes).value;
    bool error = false;
    {
        NativeWait wait(ctx);
        {
            std::lock_guard lock(stream.mutex);
            closed = stream.closed;
            if (!closed)
                ++stream.active;
        }
        if (!closed) {
            sigset_t blocked, previous, pending;
            sigemptyset(&blocked);
            sigaddset(&blocked, SIGPIPE);
            const bool masked = pthread_sigmask(SIG_BLOCK, &blocked, &previous) == 0;
            bool was_pending = false;
            if (masked && sigpending(&pending) == 0)
                was_pending = sigismember(&pending, SIGPIPE) == 1;
            std::size_t offset = 0;
            int write_error = 0;
            while (offset < data.size()) {
                auto n = ::write(stream.fd, data.data() + offset, data.size() - offset);
                if (n < 0 && errno == EINTR)
                    continue;
                if (n <= 0) {
                    write_error = n < 0 ? errno : EIO;
                    error = true;
                    break;
                }
                offset += static_cast<std::size_t>(n);
            }
            // Consume only a signal generated by this write; leave the host's
            // process-wide disposition and previously pending signals alone.
            if (masked) {
                if (write_error == EPIPE && !was_pending) {
                    const timespec immediate{0, 0};
                    while (sigtimedwait(&blocked, nullptr, &immediate) < 0 && errno == EINTR) {
                    }
                }
                pthread_sigmask(SIG_SETMASK, &previous, nullptr);
            }
            {
                std::lock_guard lock(stream.mutex);
                --stream.active;
                if (!stream.active)
                    stream.idle.notify_all();
            }
        }
    }
    if (closed) {
        closed_error(ctx, out);
        return;
    }
    if (error) {
        io_error(ctx, out);
        return;
    }
    make_int(ctx, static_cast<std::int64_t>(ctx.payload<StrObject>(text).value.size()), out);
}
enum class Operation { Flush, Close, Isatty, Fileno };
template <Operation op>
void operation(Attachment &ctx, Handle, std::span<const Value> args, ReturnSlot &out)
{
    RootScope roots(ctx);
    auto self = roots.root(args[0]);
    auto &stream = ctx.payload<StdTextIO>(self);
    bool closed, tty = false;
    {
        NativeWait wait(ctx);
        std::unique_lock lock(stream.mutex);
        closed = stream.closed;
        if constexpr (op == Operation::Close) {
            stream.closed = true;
            stream.idle.wait(lock, [&] { return stream.active == 0; });
        }
    }
    if constexpr (op == Operation::Isatty) {
        if (!closed) {
            NativeWait wait(ctx);
            tty = ::isatty(stream.fd) == 1;
        }
    }
    if constexpr (op != Operation::Close) {
        if (closed) {
            closed_error(ctx, out);
            return;
        }
    }
    if constexpr (op == Operation::Isatty)
        out.ok(ctx.builtin(tty ? CoreObject::True : CoreObject::False));
    else if constexpr (op == Operation::Fileno)
        make_int(ctx, stream.fd, out);
    else
        out.ok(ctx.builtin(CoreObject::None));
}
void closed_get(Attachment &ctx, Value value, ReturnSlot &out)
{
    RootScope roots(ctx);
    auto self = roots.root(value);
    auto &stream = ctx.payload<StdTextIO>(self);
    bool closed;
    {
        NativeWait wait(ctx);
        std::lock_guard lock(stream.mutex);
        closed = stream.closed;
    }
    out.ok(ctx.builtin(closed ? CoreObject::True : CoreObject::False));
}
void encoding_get(Attachment &ctx, Value, ReturnSlot &out)
{
    make_str(ctx, U"utf-8", out);
}
void errors_get(Attachment &ctx, Value, ReturnSlot &out)
{
    make_str(ctx, U"strict", out);
}
bool invoke(Attachment &ctx, Handle object, const char32_t *name, std::span<const Value> args,
            ReturnSlot &out)
{
    RootScope roots(ctx);
    ReturnSlot key(ctx), method(ctx);
    make_str(ctx, name, key);
    get_attribute(ctx, object, roots.root(key.value()), method);
    if (failed(method)) {
        out.raised(method.exception());
        return false;
    }
    call(ctx, roots.root(method.value()), {args, {}}, out);
    return !failed(out);
}
bool write_object(Attachment &ctx, Handle file, Handle value, ReturnSlot &out)
{
    RootScope roots(ctx);
    ReturnSlot key(ctx), method(ctx), text(ctx);
    make_str(ctx, U"write", key);
    get_attribute(ctx, file, roots.root(key.value()), method);
    if (failed(method)) {
        out.raised(method.exception());
        return false;
    }
    // PyFile_WriteObject resolves write before converting the value to text.
    str(ctx, value, text);
    if (failed(text)) {
        out.raised(text.exception());
        return false;
    }
    const Value argument = text.value();
    call(ctx, roots.root(method.value()), {{&argument, 1}, {}}, out);
    return !failed(out);
}
