void initialize_stdio(Attachment &ctx, Handle module, ReturnSlot &out)
{
    RootScope roots(ctx);
    std::vector<Handle> core;
    for (std::size_t i = 0; i < core_count; ++i)
        core.push_back(roots.root(ctx.builtin(static_cast<CoreObject>(i))));
    NativeTypeSpec spec{{"_StandardTextIO"}, LayoutDescriptor::of<StdTextIO>()};
    spec.type.module = U"sys";
    ReturnSlot result(ctx);
    create_native_type(ctx, spec, result);
    if (failed(result)) {
        out.raised(result.exception());
        return;
    }
    auto type = roots.root(result.value());
    SignatureLayout unary;
    unary.parameters = {{U"self", ParameterKind::PositionalOnly}};
    auto binary = unary;
    binary.parameters.push_back({U"text", ParameterKind::PositionalOnly});
    install_native_attribute(ctx, core, type, U"write", binary, write_entry);
    install_native_attribute(ctx, core, type, U"flush", unary, operation<Operation::Flush>);
    install_native_attribute(ctx, core, type, U"close", unary, operation<Operation::Close>);
    install_native_attribute(ctx, core, type, U"isatty", unary, operation<Operation::Isatty>);
    install_native_attribute(ctx, core, type, U"fileno", unary, operation<Operation::Fileno>);
    install_native_field(ctx, core, type, U"closed", closed_get);
    install_native_field(ctx, core, type, U"encoding", encoding_get);
    install_native_field(ctx, core, type, U"errors", errors_get);
    const char32_t *names[] = {U"stdin", U"stdout", U"stderr"};
    const char32_t *originals[] = {U"__stdin__", U"__stdout__", U"__stderr__"};
    for (int fd = 0; fd != 3; ++fd) {
        ctx.allocate_instance<StdTextIO>(type, result, fd);
        auto stream = roots.root(result.value());
        for (auto name : {names[fd], originals[fd]}) {
            make_str(ctx, name, result);
            name_store(ctx, module_dict(ctx, module.get(ctx)), result.value(), stream.get(ctx));
        }
    }
    out.ok(ctx.builtin(CoreObject::None));
}
void print_builtin(Attachment &ctx, Handle, std::span<const Value> args, ReturnSlot &out)
{
    RootScope roots(ctx);
    auto none = ctx.builtin(CoreObject::None);
    ReturnSlot temp(ctx), file_slot(ctx);
    // CPython's generated argument wrapper converts flush before entering print.
    truth(ctx, roots.root(args[3]), temp);
    if (failed(temp)) {
        out.raised(temp.exception());
        return;
    }
    const bool flush = temp.value() == ctx.builtin(CoreObject::True);
    Handle file = roots.root(args[2]);
    if (args[2] == none) {
        import_module(ctx, U"sys", temp);
        if (failed(temp)) {
            out.raised(temp.exception());
            return;
        }
        auto sys = roots.root(temp.value());
        make_str(ctx, U"stdout", temp);
        get_attribute(ctx, sys, roots.root(temp.value()), file_slot);
        if (failed(file_slot)) {
            out.raised(file_slot.exception());
            return;
        }
        file = roots.root(file_slot.value());
        if (file.get(ctx) == none) {
            out.ok(none);
            return;
        }
    }
    if ((args[0] != none && !is_text(ctx, args[0])) ||
        (args[1] != none && !is_text(ctx, args[1]))) {
        raise_error(ctx, CoreObject::TypeErrorType, U"sep and end must be None or strings", out);
        return;
    }
    make_str(ctx, U" ", temp);
    auto sep = roots.root(args[0] == none ? temp.value() : args[0]);
    make_str(ctx, U"\n", temp);
    auto end = roots.root(args[1] == none ? temp.value() : args[1]);
    auto tuple = roots.root(args[4]);
    const auto &items = ctx.payload<TupleObject>(tuple).items;
    for (std::size_t i = 0; i < items.size(); ++i) {
        if (i && !write_object(ctx, file, sep, out))
            return;
        if (!write_object(ctx, file, roots.root(items[i]), out))
            return;
    }
    if (!write_object(ctx, file, end, out))
        return;
    if (flush && !invoke(ctx, file, U"flush", {}, out))
        return;
    out.ok(none);
}
