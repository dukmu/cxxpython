"""Generate Unicode 15.0.0 identifier or repr category range data."""

import argparse
import hashlib
from pathlib import Path


def generate(source, property_="identifier"):
    data = source.read_bytes()
    lines = data.decode("utf-8").splitlines()
    filename = "DerivedCoreProperties" if property_ == "identifier" else "DerivedGeneralCategory"
    if lines[0] != f"# {filename}-15.0.0.txt":
        raise ValueError(f"expected Unicode 15.0.0 {filename}.txt")
    properties = {"XID_Start": [], "XID_Continue": []} if property_ == "identifier" else {"non_printable": []}
    for line in lines:
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        codepoints, name = (item.strip() for item in record.split(";"))
        if property_ == "identifier":
            if name not in properties:
                continue
        else:
            if name[0] not in "CZ":
                continue
            name = "non_printable"
        bounds = codepoints.split("..")
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        ranges = properties[name]
        if property_ == "identifier" and ranges and ranges[-1][1] + 1 == first:
            ranges[-1] = (ranges[-1][0], last)
        else:
            ranges.append((first, last))
    if property_ != "identifier":
        merged = []
        for first, last in sorted(properties["non_printable"]):
            if merged and merged[-1][1] + 1 >= first:
                merged[-1] = (merged[-1][0], max(merged[-1][1], last))
            else:
                merged.append((first, last))
        properties["non_printable"] = merged
    path = filename if property_ == "identifier" else "extracted/" + filename
    output = [
        "// Generated by Tools/scripts/generate_unicode.py; do not edit.",
        f"// Unicode 15.0.0, https://www.unicode.org/Public/15.0.0/ucd/{path}.txt",
        "// Copyright 2022 Unicode, Inc. See doc/licenses/unicode.txt.",
        "// Source SHA-256: " + hashlib.sha256(data).hexdigest(),
    ]
    for name, ranges in properties.items():
        output.append("constexpr std::pair<char32_t, char32_t> " + name.lower() + "[] = {")
        output.extend(f"    {{0x{first:x}, 0x{last:x}}}," for first, last in ranges)
        output.append("};")
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--property", choices=("identifier", "repr"), default="identifier")
    args = parser.parse_args()
    args.output.write_text(generate(args.source, args.property), encoding="ascii")
