"""Generate Unicode 15.0 NFKC tables using CPython's unicodedata module."""

import argparse
from pathlib import Path
import unicodedata


def generate():
    if unicodedata.unidata_version != "15.0.0":
        raise RuntimeError("expected CPython unicodedata version 15.0.0")

    decompositions = []
    decomposition_data = []
    combining = []
    compositions = []
    for cp in range(0x110000):
        char = chr(cp)
        ccc = unicodedata.combining(char)
        if ccc:
            combining.append((cp, ccc))
        # Hangul decomposition and composition are handled algorithmically.
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        normalized = unicodedata.normalize("NFKD", char)
        if normalized != char:
            decompositions.append((cp, len(decomposition_data), len(normalized)))
            decomposition_data.extend(map(ord, normalized))
        raw = unicodedata.decomposition(char)
        if raw and not raw.startswith("<"):
            parts = [int(part, 16) for part in raw.split()]
            if len(parts) == 2 and unicodedata.normalize("NFC", "".join(map(chr, parts))) == char:
                compositions.append((parts[0], parts[1], cp))

    lines = [
        "// Generated by Tools/scripts/generate_normalization.py; do not edit.",
        "// Unicode 15.0.0; Unicode data copyright and license: doc/licenses/unicode.txt.",
        "struct NormalizationDecomposition { char32_t point; unsigned offset; unsigned length; };",
        "struct NormalizationCombining { char32_t point; unsigned value; };",
        "struct NormalizationComposition { char32_t first; char32_t second; char32_t result; };",
        "constexpr char32_t normalization_decomposition_data[] = {",
    ]
    for offset in range(0, len(decomposition_data), 12):
        lines.append("    " + ", ".join(f"0x{x:x}" for x in decomposition_data[offset:offset + 12]) + ",")
    lines.append("};")
    lines.append("constexpr NormalizationDecomposition normalization_decompositions[] = {")
    lines.extend(f"    {{0x{cp:x}, {offset}, {length}}}," for cp, offset, length in decompositions)
    lines.append("};")
    lines.append("constexpr NormalizationCombining normalization_combining[] = {")
    lines.extend(f"    {{0x{cp:x}, {ccc}}}," for cp, ccc in combining)
    lines.append("};")
    lines.append("constexpr NormalizationComposition normalization_compositions[] = {")
    lines.extend(f"    {{0x{a:x}, 0x{b:x}, 0x{result:x}}}," for a, b, result in sorted(compositions))
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(), encoding="ascii")
