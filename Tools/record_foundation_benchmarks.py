#!/usr/bin/env python3
"""Capture bench_foundation output and regenerate CSV/Markdown from raw runs."""

import argparse
import csv
from datetime import date, datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import statistics
import subprocess


def parse_output(output, series, sample):
    rows = []
    for line in output.splitlines():
        if not line.strip():
            continue
        fields = dict(token.split("=", 1) for token in line.split())
        probe = next(iter(fields))
        workers = next((value for key, value in fields.items() if key.endswith("_workers")), "")
        for metric, value in fields.items():
            if metric.endswith("live_set_check") and value != "ok":
                raise ValueError(f"{metric}={value}")
            rows.append([series, sample, probe, workers, metric, value])
    if not rows:
        raise ValueError("benchmark produced no metrics")
    return rows


def render_report(rows, failures):
    groups = {}
    for series, sample, probe, workers, metric, value in rows:
        if metric.endswith("_ns"):
            unit, scale = "ms", 1_000_000
        elif metric.endswith("_bytes"):
            unit, scale = "bytes", 1
        elif metric == "process_peak_rss_kib":
            unit, scale = "KiB", 1
        else:
            continue
        groups.setdefault((series, probe, workers, metric, unit), []).append(float(value) / scale)
    lines = ["# Foundation Benchmark Report", "",
             "Generated by Tools/record_foundation_benchmarks.py; do not edit tables.", "",
             f"Failed runs retained in raw data: {failures}.", "",
             "Timings are per complete probe, not per operation. Iteration counts and correctness checks are in the CSV.",
             "Storage/native delivery probes do not establish Python VM parallelism. RSS is the whole workflow peak, not a worker/stage peak.", "",
             "| Series | Probe | Workers | Metric | Unit | Samples | Median | Min | Max |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for key, values in sorted(groups.items()):
        series, probe, workers, metric, unit = key
        lines.append(f"| {series} | {probe} | {workers or '-'} | {metric} | {unit} | {len(values)} | "
                     f"{statistics.median(values):.3f} | {min(values):.3f} | {max(values):.3f} |")
    lines += ["", "## Fixed-Work Scaling", "",
              "Derived from median wall/process CPU times. CPU/wall is not a speedup; 1-worker wall time is the speedup baseline.", "",
              "| Series | Probe | Workers | Wall ms | CPU/Wall | Speedup | Efficiency |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for (series, probe, workers, metric, unit), values in sorted(groups.items()):
        baseline = groups.get((series, probe, "1", "wall_ns", "ms"))
        cpu = groups.get((series, probe, workers, "process_cpu_ns", "ms"))
        if metric != "wall_ns" or not workers or not baseline or not cpu:
            continue
        wall = statistics.median(values)
        speedup = statistics.median(baseline) / wall
        lines.append(f"| {series} | {probe} | {workers} | {wall:.3f} | {statistics.median(cpu) / wall:.3f} | "
                     f"{speedup:.3f} | {speedup / int(workers):.3f} |")
    return "\n".join(lines) + "\n"


def generate_tables(raw, output_dir, stamp):
    runs = [json.loads(line) for line in raw.read_text().splitlines()] if raw.exists() else []
    rows = [row for run in runs if run["exit_code"] == 0
            for row in parse_output(run["output"], run["series"], run["sample"])]
    csv_path = output_dir / f"foundation-results-{stamp}.csv"
    with csv_path.open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["series", "sample", "probe", "workers", "metric", "value"])
        writer.writerows(rows)
    report = output_dir / f"foundation-report-{stamp}.md"
    report.write_text(render_report(rows, sum(run["exit_code"] != 0 for run in runs)))
    return runs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--binary", type=Path)
    source.add_argument("--input", type=Path, action="append", help="Import captured key=value output, without claiming binary provenance")
    source.add_argument("--report-only", action="store_true")
    parser.add_argument("--series")
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--date", default=date.today().isoformat())
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "doc/benchmarks")
    args = parser.parse_args()
    if not args.report_only and (not args.series or not re.fullmatch(r"[A-Za-z0-9_.-]+", args.series)):
        parser.error("--series must be a nonempty ASCII label")
    if args.runs < 1:
        parser.error("--runs must be positive")
    date.fromisoformat(args.date)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    raw = args.output_dir / f"foundation-runs-{args.date}.jsonl"
    runs = generate_tables(raw, args.output_dir, args.date)
    if args.report_only:
        return
    sample = max((run["sample"] for run in runs if run["series"] == args.series), default=0)
    command = None
    digest = None
    build = {}
    if args.binary:
        binary = args.binary.resolve()
        digest = hashlib.sha256(binary.read_bytes()).hexdigest()
        cache = binary.parent / "CMakeCache.txt"
        if cache.exists():
            for line in cache.read_text().splitlines():
                if line.startswith(("CMAKE_BUILD_TYPE:", "CMAKE_CXX_COMPILER:", "CMAKE_CXX_FLAGS:", "CMAKE_CXX_FLAGS_RELEASE:")):
                    key, value = line.split("=", 1)
                    build[key.split(":", 1)[0]] = value
        command = [str(binary)]
        if Path("/usr/bin/time").exists():
            command = ["/usr/bin/time", "-f", "process_peak_rss_kib=%M", *command]
    sources = args.input if args.input else [None] * args.runs
    for source_path in sources:
        sample += 1
        if source_path:
            output, exit_code = source_path.read_text(), 0
        else:
            result = subprocess.run(command, capture_output=True, text=True)
            output, exit_code = result.stdout + result.stderr, result.returncode
        if exit_code == 0:
            parse_output(output, args.series, sample)
        record = dict(series=args.series, sample=sample, output=output, exit_code=exit_code,
                      captured_at=datetime.now(timezone.utc).isoformat(), platform=platform.platform(),
                      logical_cpus=os.cpu_count(), command=command, binary_sha256=digest, build=build,
                      imported_from=str(source_path) if source_path else None)
        with raw.open("a") as stream:
            stream.write(json.dumps(record, ensure_ascii=True) + "\n")
        generate_tables(raw, args.output_dir, args.date)
        if exit_code:
            raise SystemExit(f"benchmark failed with {exit_code}; raw output retained in {raw}")
    print(args.output_dir / f"foundation-report-{args.date}.md")


if __name__ == "__main__":
    main()
