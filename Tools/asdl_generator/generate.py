"""Generate native Python AST schema from the pinned CPython ASDL, without hashes."""

import argparse
from pathlib import Path

import asdl

ROOT = Path(__file__).resolve().parents[2]


def cpp(name):
    return name + '_' if name in ('operator', 'int') else name


def generate():
    schema = asdl.parse(str(ROOT / 'Grammar/Python.asdl'))
    if not asdl.check(schema):
        raise SystemExit('invalid Python ASDL')
    nodes = [('AST', 'AST', [], [])]
    for definition in schema.dfns:
        value = definition.value
        if isinstance(value, asdl.Sum):
            nodes.append((definition.name, 'AST', [], value.attributes))
            nodes.extend((node.name, definition.name, node.fields, value.attributes)
                         for node in value.types)
        else:
            nodes.append((definition.name, 'AST', value.fields, value.attributes))
    names = ['identifier', 'int', 'string', 'constant'] + [d.name for d in schema.dfns]
    def signature(name, fields):
        if not fields:
            return name
        parts = [f'{field.type}{"*" if field.seq else "?" if field.opt else ""} {field.name}'
                 for field in fields]
        return name + '(' + ', '.join(parts) + ')'
    docs = {'AST': ''}
    for definition in schema.dfns:
        value = definition.value
        if isinstance(value, asdl.Sum):
            definitions = [signature(node.name, node.fields) for node in value.types]
            docs[definition.name] = definition.name + ' = ' + '\n     | '.join(definitions)
            docs.update((node.name, signature(node.name, node.fields)) for node in value.types)
        else:
            docs[definition.name] = signature(definition.name, value.fields)
    lines = ['// Generated by Tools/asdl_generator/generate.py from CPython 3.12.14.',
             '// PSF license: doc/licenses/python-3.12.14.txt. Do not edit.',
             'enum class Kind { ' + ', '.join(cpp(n[0]) for n in nodes) + ', Count };',
             'enum class FieldType { ' + ', '.join(cpp(n) for n in names) + ' };',
             'struct FieldInfo { std::u32string_view name; FieldType type; bool sequence, optional; };',
             'struct NodeInfo { Kind kind, base; std::string_view name, documentation; bool abstract; '
             'std::span<const FieldInfo> fields, attributes; };']
    for name, base, fields, attributes in nodes:
        for suffix, values in [('fields', fields), ('attributes', attributes)]:
            lines.append(f'inline constexpr std::array<FieldInfo, {len(values)}> {cpp(name)}_{suffix}{{{{')
            for field in values:
                lines.append(f'{{U"{field.name}", FieldType::{cpp(field.type)}, '
                             f'{str(field.seq).lower()}, {str(field.opt).lower()}}},')
            lines.append('}};')
    lines.append(f'inline constexpr std::array<NodeInfo, {len(nodes)}> node_info{{{{')
    for name, base, _, _ in nodes:
        doc = docs[name].replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        abstract = name == 'AST' or (name in schema.types and isinstance(schema.types[name], asdl.Sum))
        lines.append(f'{{Kind::{cpp(name)}, Kind::{cpp(base)}, "{name}", "{doc}", {str(abstract).lower()}, '
                     f'{cpp(name)}_fields, {cpp(name)}_attributes}},')
    lines.extend(['}};', 'inline const NodeInfo &info(Kind kind) {',
                  'return node_info.at(static_cast<std::size_t>(kind));', '}',
                  'inline std::optional<Kind> node_category(FieldType field) {', 'switch (field) {'])
    for definition in schema.dfns:
        lines.append(f'case FieldType::{cpp(definition.name)}: return Kind::{cpp(definition.name)};')
    lines.extend(['default: return {};', '}', '}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'Include/internal/ast_generated.inc'
    text = generate()
    if args.check:
        if not output.exists() or output.read_text() != text:
            raise SystemExit('AST generated schema differs; run Tools/asdl_generator/generate.py')
    else:
        output.write_text(text)
    print('Python ASDL schema verified' if args.check else 'Python ASDL schema generated')


if __name__ == '__main__':
    main()
